import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { configureStore } from '@reduxjs/toolkit';
import { store } from '../store/store';
import { steelApi } from '../api/steelApi';
import { openDefinition, updateDraft } from '../store/workflowEditor';
import { openSpec } from '../store/templateEditor';
import { acceptAccount, configureRuntime, endAccount } from './session';
const config = { mode: 'account' as const, firebase: { apiKey: 'test-public', projectId: 'test-project', authDomain: 'test-project.firebaseapp.com' } };
beforeEach(() => { sessionStorage.clear(); configureRuntime({ mode: 'local' }); });
afterEach(() => { endAccount(); vi.unstubAllGlobals(); });
it('preserves local recovery while clearing account editors, templates and API cache on signout', async () => {
  const local = { workflow_id: 'local-work', inputs: [], steps: [] };
  store.dispatch(openDefinition({ workflowId: 'local-work', version: null, definition: local }));
  store.dispatch(updateDraft({ ...local, name: 'Unsaved local work' }));
  const savedLocal = sessionStorage.getItem('steel.workflow-draft.local.v1'); expect(savedLocal).toContain('Unsaved local work');
  configureRuntime(config); acceptAccount({ localId: 'alice', email: 'alice@example.invalid', idToken: 'alice-secret' });
  expect(store.getState().workflowEditor.draft).toBeNull();
  store.dispatch(openDefinition({ workflowId: 'alice-work', version: 1, definition: { ...local, workflow_id: 'alice-work' } }));
  store.dispatch(openSpec({ templateId: 'alice-template', version: null, kind: 'document', spec: { schema: 'steel-doc/1', template_id: 'alice-template', version: 1 } as never }));
  vi.stubGlobal('fetch', vi.fn().mockResolvedValue(new Response('{"skills":[{"name":"alice-skill"}]}')));
  await store.dispatch(steelApi.endpoints.listSkills.initiate());
  expect(JSON.stringify(store.getState().steelApi)).toContain('alice-skill');
  endAccount();
  expect(store.getState().workflowEditor.draft).toBeNull(); expect(store.getState().templateEditor.spec).toBeNull();
  expect(JSON.stringify(store.getState().steelApi)).not.toContain('alice-skill');
  expect(sessionStorage.getItem('steel.workflow-draft.local.v1')).toBe(savedLocal);
  expect(sessionStorage.getItem('steel.workflow-draft.v1')).toBeNull();
  expect(JSON.stringify(sessionStorage)).not.toContain('alice-work');
  configureRuntime({ mode: 'local' }); expect(store.getState().workflowEditor.draft?.name).toBe('Unsaved local work');
});
it('never dispatches transport Request metadata or bearer tokens in Redux actions/state', async () => {
  configureRuntime(config); acceptAccount({ localId: 'alice', email: 'alice@example.invalid', idToken: 'unique-credential-value' });
  const actions: unknown[] = [];
  const capture = () => (next: (action: unknown) => unknown) => (action: unknown) => { actions.push(action); return next(action); };
  const isolated = configureStore({ reducer: { [steelApi.reducerPath]: steelApi.reducer }, middleware: (getDefault) => getDefault().concat(capture, steelApi.middleware) });
  vi.stubGlobal('fetch', vi.fn().mockResolvedValue(new Response('{"skills":[]}')));
  await isolated.dispatch(steelApi.endpoints.listSkills.initiate());
  expect(JSON.stringify(actions)).not.toContain('unique-credential-value');
  for (const action of actions as any[]) expect(action.meta?.baseQueryMeta).toBeUndefined();
  expect(JSON.stringify(isolated.getState())).not.toContain('unique-credential-value');
});
